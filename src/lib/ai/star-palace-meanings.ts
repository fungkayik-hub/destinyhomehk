export function lookupStarPalaceMeaning(
  star: string,
  palace: PalaceName,
): string | null {
  const map = STAR_PALACE_MEANINGS[star as MajorStarName];
  if (!map) return null;
  return map[palace] ?? null;
}

/** 該宮主星含義（多主星就併） */
export function meaningsForPalaceMajors(palace: PalaceInfo): string[] {
  return palace.stars
    .filter((s) => s.type !== "minor")
    .map((s) => {
      const meaning = lookupStarPalaceMeaning(s.name, palace.name);
      if (!meaning) return null;
      const bright = s.brightness ? `(${s.brightness})` : "";
      return `${s.name}${bright}@${palace.name}：${meaning}`;
    })
    .filter((x): x is string => Boolean(x));
}

/** 注入 AI：只列本盤有出現嘅「主星@宮」，慳 token */
export function formatStarPalaceHintsForChart(chart: ZiWeiChart): string {
  const lines: string[] = [];
  for (const palace of chart.palaces) {
    for (const line of meaningsForPalaceMajors(palace)) {
      lines.push(`• ${line}`);
    }
  }
  if (lines.length === 0) return "";
  return [
    "════ 本盤主星×宮位含義（寫該宮必須跟呢句，唔好套錯宮）════",
    "同一星坐唔同宮意思唔同；寫遷移唔好抄命宮性格句。",
    "條件：天機入陷坐遷移 → 另加「一生漂泊、好似雀鳥、走嚟走去、容易迷路」。",
    ...lines,
  ].join("\n");
}

/** Fallback 用：一句星義（無就 null） */
export function primaryStarPalaceMeaning(palace: PalaceInfo): string | null {
  const major = palace.stars.find((s) => s.type !== "minor");
  if (!major) return null;
  return lookupStarPalaceMeaning(major.name, palace.name);
}

export function allStarPalaceMeaningCount(): number {
  let n = 0;
  for (const star of MAJOR_STARS) {
    for (const p of PALACES) {
      if (STAR_PALACE_MEANINGS[star][p]) n++;
    }
  }
  return n;
}
