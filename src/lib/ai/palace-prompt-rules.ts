/** 注入 AI system prompt 用嘅十二宮規則全文 */
export function formatPalacePromptRulesBlock(
  which: "ming" | "others" | "all" = "all",
): string {
  const names =
    which === "ming"
      ? (["命宮"] as PalaceName[])
      : which === "others"
        ? PALACES.filter((p) => p !== "命宮")
        : [...PALACES];

  const lines: string[] = [
    "【十二宮專屬寫作規則 — 每宮必須跟自己嗰條，唔好九唔搭八】",
    "每宮主題、必寫、條件、懸念都唔同；寫完一宮要似『講緊呢個生活範疇』，唔好用同一套性格標籤套晒十二宮。",
    "",
  ];

  for (const name of names) {
    const r = PALACE_PROMPT_RULES[name];
    lines.push(`── ${name}（${r.theme}）──`);
    for (const m of r.must) lines.push(`• 必寫：${m}`);
    if (r.conditional?.length) {
      for (const c of r.conditional) lines.push(`• 條件：${c}`);
    }
    if (r.avoid?.length) {
      for (const a of r.avoid) lines.push(`• 禁止：${a}`);
    }
    lines.push(`• 懸念方向：${r.cliffhanger}`);
    lines.push("");
  }

  return lines.join("\n").trim();
}

