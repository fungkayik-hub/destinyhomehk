function main() {
  const db = JSON.parse(fs.readFileSync(OUT, "utf8"));
  let updated = 0;
  let added = 0;

  const starSlugs = new Set(STAR_ARTICLES.map((s) => s.slug));
  db.articles = db.articles.filter(
    (a) => !(a.category === "stars" && a.slug === "談七殺星-紫微斗數14主星" && !starSlugs.has(a.slug)),
  );

  for (const star of STAR_ARTICLES) {
    const contentHtml = buildContent(star);
    const len = stripHtml(contentHtml).length;
    if (len < 500 || len > 800) {
      console.warn(`⚠ ${star.slug} 字數 ${len}（目標 500–800）`);
    }

    const article = {
      slug: star.slug,
      category: "stars",
      title: star.title,
      content: contentHtml,
      image: star.image,
      publishedAt: TODAY,
      sourceUrl: `https://www.destinyhomehk.com/academy/stars/${encodeURIComponent(star.slug)}`,
      type: "blog",
    };

    const idx = db.articles.findIndex(
      (a) => a.category === "stars" && a.slug === star.slug,
    );

    if (idx >= 0) {
      db.articles[idx] = { ...db.articles[idx], ...article };
      updated++;
      console.log(`✓ 更新 ${star.slug}（${len} 字）`);
    } else {
      db.articles.unshift(article);
      added++;
      console.log(`+ 新增 ${star.slug}（${len} 字）`);
    }

    fs.mkdirSync(DONE_DIR, { recursive: true });
    const backupPath = path.join(DONE_DIR, `${TODAY}-${star.slug}.json`);
    fs.writeFileSync(
      backupPath,
      JSON.stringify(
        {
          title: star.title,
          category: "stars",
          slug: star.slug,
          publishedAt: TODAY,
          image: star.image,
          keyword: star.keyword,
          contentHtml,
        },
        null,
        2,
      ),
      "utf8",
    );
  }

  fs.writeFileSync(OUT, JSON.stringify(db, null, 2), "utf8");
  console.log(`\n完成：更新 ${updated} 篇、新增 ${added} 篇 · 共處理 ${STAR_ARTICLES.length} 粒主星`);
}

main();
