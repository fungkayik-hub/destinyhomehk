function stripHtml(html) {
  return html.replace(/<[^>]+>/g, "").replace(/\s+/g, "");
}

function main() {
  const db = JSON.parse(fs.readFileSync(OUT, "utf8"));
  const today = "2026-07-07";
  let updated = 0;
  let added = 0;

  for (const star of STAR_ARTICLES) {
    const len = stripHtml(star.contentHtml).length;
    if (len < 500) {
      console.warn(`⚠ ${star.slug} 只有 ${len} 字，未達 500`);
    }

    const article = {
      slug: star.slug,
      category: "stars",
      title: star.title,
      content: star.contentHtml,
      image: star.image,
      publishedAt: today,
      sourceUrl: `https://www.destinyhomehk.com/academy/stars/${encodeURIComponent(star.slug)}`,
      type: "blog",
    };

    const idx = db.articles.findIndex(
      (a) => a.category === "stars" && a.slug === star.slug,
    );

    if (idx >= 0) {
      db.articles[idx] = { ...db.articles[idx], ...article };
      updated++;
      console.log(`✓ 更新 ${star.slug}（${len} 字）`);
    } else {
      db.articles.unshift(article);
      added++;
      console.log(`+ 新增 ${star.slug}（${len} 字）`);
    }

    // 備份到 inbox/done
    fs.mkdirSync(DONE_DIR, { recursive: true });
    const backupPath = path.join(DONE_DIR, `${today}-${star.slug}.json`);
    fs.writeFileSync(
      backupPath,
      JSON.stringify(
        {
          title: star.title,
          category: "stars",
          slug: star.slug,
          publishedAt: today,
          image: star.image,
          keyword: star.keyword,
          contentHtml: star.contentHtml,
        },
        null,
        2,
      ),
      "utf8",
    );
  }

  fs.writeFileSync(OUT, JSON.stringify(db, null, 2), "utf8");
  console.log(`\n完成：更新 ${updated} 篇、新增 ${added} 篇 · 共處理 ${STAR_ARTICLES.length} 粒主星`);
}

main();
